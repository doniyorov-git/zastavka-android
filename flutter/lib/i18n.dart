const _dicts = {'en': _en, 'ru': _ru, 'zh': _zh};

class I18n extends ChangeNotifier {
  I18n() {
    _load();
  }

  String _lang = 'en';
  String get lang => _lang;

  Future<void> _load() async {
    final prefs = await SharedPreferences.getInstance();
    final stored = prefs.getString(_storageKey);
    if (stored == 'en' || stored == 'ru' || stored == 'zh') {
      _lang = stored!;
      notifyListeners();
    }
  }

  Future<void> setLang(String code) async {
    if (code != 'en' && code != 'ru' && code != 'zh') return;
    _lang = code;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_storageKey, code);
    notifyListeners();
  }

  String t(String key, [Map<String, String>? vars]) {
    var text = _dicts[_lang]?[key] ?? _en[key] ?? key;
    if (vars != null) {
      vars.forEach((k, v) {
        text = text.replaceAll('{$k}', v);
      });
    }
    return text;
  }
}
